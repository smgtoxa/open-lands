// Game text: the string tables in LANDS.<lang> and LEVEL<n>.<lang>, and the two-stage compression
// they use - a nibble index into a table of common letters, then a second pass for the rest.
// Transliterated from decodeString1/decodeString2 and getLangString in src/game/engine.mjs.
namespace LolCore;

public static class GameStrings
{
    private static readonly byte[] Decode1 = { 0x20, 0x65, 0x74, 0x61, 0x69, 0x6e, 0x6f, 0x73, 0x72, 0x6c, 0x68, 0x63, 0x64, 0x75, 0x70, 0x6d };

    private static readonly byte[] Decode2 = { 0x74, 0x61, 0x73, 0x69, 0x6f, 0x20, 0x77, 0x62, 0x20, 0x72, 0x6e, 0x73, 0x64, 0x61, 0x6c, 0x6d, 0x68, 0x20, 0x69, 0x65, 0x6f, 0x72, 0x61, 0x73, 0x6e, 0x72, 0x74, 0x6c, 0x63, 0x20, 0x73, 0x79, 0x6e, 0x73, 0x74, 0x63, 0x6c, 0x6f, 0x65, 0x72, 0x20, 0x64, 0x74, 0x67, 0x65, 0x73, 0x69, 0x6f, 0x6e, 0x72, 0x20, 0x75, 0x66, 0x6d, 0x73, 0x77, 0x20, 0x74, 0x65, 0x70, 0x2e, 0x69, 0x63, 0x61, 0x65, 0x20, 0x6f, 0x69, 0x61, 0x64, 0x75, 0x72, 0x20, 0x6c, 0x61, 0x65, 0x69, 0x79, 0x6f, 0x64, 0x65, 0x69, 0x61, 0x20, 0x6f, 0x74, 0x72, 0x75, 0x65, 0x74, 0x6f, 0x61, 0x6b, 0x68, 0x6c, 0x72, 0x20, 0x65, 0x69, 0x75, 0x2c, 0x2e, 0x6f, 0x61, 0x6e, 0x73, 0x72, 0x63, 0x74, 0x6c, 0x61, 0x69, 0x6c, 0x65, 0x6f, 0x69, 0x72, 0x61, 0x74, 0x70, 0x65, 0x61, 0x6f, 0x69, 0x70, 0x20, 0x62, 0x6d };

    public static string DecodeString1(byte[] buffer, int offset)
    {
        var outText = new System.Text.StringBuilder();
        for (int i = offset; i < buffer.Length && buffer[i] != 0; i += 1)
        {
            int c = buffer[i];
            if ((c & 0x80) != 0)
            {
                c &= 0x7f;
                outText.Append((char)Decode1[(c & 0x78) >> 3]);
                c = Decode2[c];
            }
            outText.Append((char)c);
        }
        return outText.ToString();
    }

    public static string DecodeString2(string src)
    {
        var outText = new System.Text.StringBuilder();
        for (int i = 0; i < src.Length; i += 1)
        {
            if (src[i] == 0x1b)
            {
                i += 1;
                outText.Append((char)((src[i] + 0x7f) & 0xff));
            }
            else outText.Append(src[i]);
        }
        return outText.ToString();
    }

    /// <summary>getLangString: bit 0x4000 picks the global table, the rest the level's own.</summary>
    public static string Get(int id, byte[] landsFile, byte[] levelFile)
    {
        if (id == 0xffff) return null;
        var buffer = (id & 0x4000) != 0 ? landsFile : levelFile;
        if (buffer == null) return null;
        int realId = id & 0x3fff;
        if ((realId << 1) + 1 >= buffer.Length) return null;
        int offset = buffer[realId << 1] | (buffer[(realId << 1) + 1] << 8);
        return DecodeString2(DecodeString1(buffer, offset));
    }
}
